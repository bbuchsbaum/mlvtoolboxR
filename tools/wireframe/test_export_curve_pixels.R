suppressPackageStartupMessages(pkgload::load_all(".", quiet = TRUE))
source("tools/wireframe/export_curve_pixels.R")

root <- tempfile("curve-pixels-")
dir.create(root)
drawings <- file.path(root, "drawings")
output <- file.path(root, "output")
dir.create(drawings)
roster <- file.path(root, "roster.csv")
write.csv(data.frame(id = "photo"), roster, row.names = FALSE)
curves <- list(schema_version = 1L, contours = list(
  list(id = "0", segments = list(c(1, 1, 5, 1))),
  list(id = "1", segments = list(c(3, 1, 3, 4)))
))
for (source in c("fdog", "mlsd"))
  jsonlite::write_json(curves, file.path(drawings, paste("photo", source, "contours.json", sep = ".")), auto_unbox = TRUE)
source_drawing <- mlv_drawing(lapply(curves$contours, function(x)
  matrix(unlist(x$segments), ncol = 4L, byrow = TRUE)), 5L, 4L)
for (source in c("fdog", "mlsd"))
  png::writePNG(1.0 * rasterize(source_drawing), file.path(drawings, paste("photo", source, "drawing.png", sep = ".")))
export_curve_pixels(drawings, roster, output)
got <- jsonlite::fromJSON(file.path(output, "photo.json"), simplifyVector = FALSE)
stopifnot(identical(names(got), c("fdog", "mlsd")), length(got$fdog) == 2L)
stopifnot(identical(as.integer(got$fdog[[1]]), c(0L, 4L, 8L, 12L, 16L)))
stopifnot(identical(as.integer(got$fdog[[2]]), c(8L, 9L, 10L, 11L)))
unlink(root, recursive = TRUE)
