test_that("junction types use consistent axes and transitive equivalence", {
 d<-drawing(list(matrix(c(0,0,10,10),1),matrix(c(5,5,10,0),1)))
 j<-detect_junctions(d,merge_radius=0)
 expect_equal(j$type,"T");expect_equal(j$min_angle,90);expect_equal(j$max_angle,180)
 x<-drawing(list(matrix(c(1,6,11,6),1),matrix(c(6,1,6,11),1)))
 expect_equal(detect_junctions(x)$type,"X")
 expect_equal(detect_junctions(x)$min_angle,90)
 expect_equal(detect_junctions(rotate_drawing(x,31))$min_angle,90,tolerance=1e-10)
 y<-drawing(lapply(c(0,120,240),function(a)matrix(c(10,10,10+8*cos(a*pi/180),10-8*sin(a*pi/180)),1)))
 expect_equal(detect_junctions(y)$type,"Y")
 expect_equal(detect_junctions(y)$min_angle,120,tolerance=1e-10)
 expect_equal(length(unique(mlvtoolbox:::cpp_cluster_points(cbind(c(0,4,2),0),2))),1)
 neg<-drawing(list(matrix(c(-5,-1,-1,-5),1),matrix(c(-5,-5,-1,-1),1)))
 expect_equal(detect_junctions(neg,endpoint_radius=.1)$x,-3)
 set.seed(121)
 d<-drawing(lapply(seq_len(40),function(i)matrix(runif(4,-10,30),1)))
 s<-as.data.frame(d);z<-as.matrix(s[,c("x1","y1","x2","y2")])
 expect_equal(mlvtoolbox:::cpp_intersections(z,s$contour_index,1,.3,TRUE),
              mlvtoolbox:::cpp_intersections(z,s$contour_index,1,.3,FALSE),tolerance=1e-12)
})
test_that("circle clipping and junction segmentation conserve retained geometry", {
 d<-drawing(list(matrix(c(-10,0,10,0),1)))
 c<-clip_circle(d,2,c(0,0))
 expect_equal(as.data.frame(c)$length,4)
 expect_equal(unname(c$contours[[1]]),matrix(c(-2,0,2,0),1))
 expect_length(clip_circle(d,1,c(0,3))$contours,0)
 x<-drawing(list(matrix(c(1,6,11,6),1),matrix(c(6,1,6,11),1)))
 s<-segment_at_junctions(x)
 expect_length(s$contours,4);expect_equal(sum(as.data.frame(s)$length),20)
 quarters<-split_junction_regions(x)
 expect_equal(sum(as.data.frame(quarters$middle)$length),10)
 expect_equal(sum(as.data.frame(quarters$junction)$length),10)
})
test_that("whole-contour splits obey both budgets and models validate results", {
 d<-drawing(list(matrix(c(1,1,5,1),1),matrix(c(1,10,5,10),1),matrix(c(1,20,3,20),1)))
 s<-split_contours(d)
 expect_equal(sum(as.data.frame(s$top)$length),4)
 expect_equal(sum(as.data.frame(s$bottom)$length),2)
 expect_length(s$overlap,0)
 expect_length(split_contours(d,fraction=0)$top$ids,0)
 expect_length(split_contours(d,fraction=1)$overlap,3)
 expect_error(split_contours(d,fraction=2),"fraction")
 expect_error(subset_contours(d,c(1,1)),"repeated")
 schema<-feature_schema(feature_table(d))
 expect_equal(predict_contours(d,function(z)seq_len(nrow(z)),expected_spec=schema),1:3)
 expect_error(predict_contours(d,function(z)NA_real_,expected_spec=schema),"finite")
 z<-drawing(list(rbind(c(1,1,2,1),c(2,1,3,1),c(3,1,4,1))))
 expect_equal(nrow(simplify_contours(z,0)$contours[[1]]),1)
 set.seed(7);a<-shift_contours(z);set.seed(7);b<-shift_contours(z)
 expect_equal(a$contours,b$contours)
 expect_equal(as.data.frame(a)$length,as.data.frame(z)$length)
})

