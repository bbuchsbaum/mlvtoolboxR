drawing <- function(z) mlv_drawing(z,40,40)
test_that("geometry validates and preserves subpixel definitions", {
 d<-drawing(list(matrix(c(1.1,1.1,1.9,1.9),1)))
 expect_equal(as.data.frame(d)$orientation,315)
 expect_equal(as.data.frame(d)$length,sqrt(2)*.8)
 expect_error(drawing(list(matrix(c(1,1,1,1),1))),"zero-length")
 expect_error(drawing(list(matrix(c(NA,1,2,2),1))),"finite")
 expect_error(drawing(list(rbind(c(1,1,2,2),c(3,3,4,4)))),"connected")
 expect_length(mlv_drawing(list(matrix(c(1,1,1,1),1)),10,10,zero_length="drop")$ids,0)
 expect_error(mlv_drawing(list(),0,10),"positive")
 d<-drawing(list(rbind(c(1,1,11,1),c(11,1,11,6))))
 s<-as.data.frame(d,estimator="mlv2023")
 expect_equal(s$orientation,c(0,270));expect_equal(s$curvature,c(9,18))
 expect_equal(average_property(d,"curvature",estimator="mlv2023"),12)
 # Default vertex turning: the 90 degree turn spread once over its 7.5 px dual
 # cell (12 deg/px); segment means are 12 x 5/10 and 12 x 2.5/5 deg/px.
 t<-as.data.frame(d)
 expect_equal(t$orientation,c(0,270));expect_equal(t$length,c(10,5))
 expect_equal(t$curvature,c(6,6));expect_equal(sum(t$curvature*t$length),90)
 p<-curvature_profile(d,"turning")
 expect_equal(p$curvature,c(0,12,12,0));expect_equal(p$length,c(5,5,2.5,2.5))
 expect_equal(average_property(d,"curvature"),6)
 expect_equal(average_property(d,"length"),average_property(d,"length",estimator="mlv2023"))
 expect_error(as.data.frame(d,spec=feature_spec(),estimator="turning"),"not both")
 expect_error(average_property(d,"curvature",spec=feature_spec(),estimator="turning"),"not both")
 r<-as.data.frame(rotate_drawing(d,37),estimator="mlv2023")
 expect_equal(r$length,s$length,tolerance=1e-12)
 expect_equal(r$curvature,s$curvature,tolerance=1e-12)
 expect_equal((r$orientation-s$orientation)%%360,rep(37,2),tolerance=1e-12)
 reversed<-drawing(list(d$contours[[1]][2:1,c(3,4,1,2)]))
 expect_equal(contour_statistics(d,"orientation")$value,contour_statistics(reversed,"orientation")$value)
 expect_null(rotate_drawing(compute_contour_properties(d),10)$segment_properties)
})
