test_that("Arrow/Star junctions and independent gap thresholds are classified", {
 draw_rays<-function(angles)mlv_drawing(lapply(angles,function(a)matrix(c(10,10,10+8*cos(a*pi/180),10-8*sin(a*pi/180)),1)),30,30)
 expect_equal(detect_junctions(draw_rays(c(0,30,60)))$type,"Arrow")
 star<-detect_junctions(draw_rays(seq(0,288,by=72)))
 expect_equal(star$type,"Star");expect_equal(star$min_angle,72,tolerance=1e-10)
 gap<-function(delta)mlv_drawing(list(matrix(c(0,0,10,0),1),matrix(c(10+delta,-5,10+delta,5),1)),20,20)
 expect_equal(nrow(detect_junctions(gap(.9))),1)
 expect_equal(nrow(detect_junctions(gap(1.1))),0)
 expect_equal(nrow(detect_junctions(gap(.9),relative_epsilon=.05)),0)
})
