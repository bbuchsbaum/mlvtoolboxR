test_that("specifications are canonical, versioned and independent of input calibration", {
 s<-feature_spec()
 expect_identical(s$settings$estimator,"turning")
 expect_identical(s$definitions[["contour"]],"vertex-dual-1")
 # A specification records its estimator: one built when mlv2023 was the
 # default carries it explicitly, validates, and keeps its definition.
 old<-feature_spec(estimator="mlv2023")
 expect_identical(validate_feature_spec(unserialize(serialize(old,NULL))),old)
 expect_identical(old$definitions[["contour"]],"mlv2023-port-0.1.1")
 expect_false(identical(old$definitions,s$definitions))
 expect_identical(s$settings$branch_estimator,"mlv2023")
 expect_identical(s$settings$length_range,c(2,400))
 expect_identical(validate_feature_spec(unserialize(serialize(s,NULL))),s)
 a<-feature_spec(units="visual_degrees",pixels_per_degree=20)
 b<-feature_spec(units="visual_degrees",pixels_per_degree=40)
 expect_identical(mlvtoolbox:::.spec_semantics(a),mlvtoolbox:::.spec_semantics(b))
 expect_identical(mlvtoolbox:::.spec_scale(a),.05)
 expect_identical(mlvtoolbox:::.spec_scale(a,40),.025)
 bad<-s;bad$definitions['contour']<-"future"
 expect_error(validate_feature_spec(bad),"unsupported")
 bad<-s;bad$settings$bins<-NULL
 expect_error(validate_feature_spec(bad),"missing")
 bad<-s;bad$version<-2L
 expect_error(validate_feature_spec(bad),"unsupported")
 expect_error(validate_feature_spec(list()),"unsupported")
})
test_that("units and method parameters cannot silently contradict their definitions", {
 expect_error(feature_spec(units="visual_degrees"),"pixels_per_degree")
 for(x in list(0,-1,NA_real_,Inf,c(1,2)))expect_error(feature_spec(pixels_per_degree=x),"pixels_per_degree")
 expect_error(feature_spec(properties=c("length","length")),"repeated")
 expect_error(feature_spec(properties="unknown"),"properties")
 expect_error(feature_spec(normalize=NA),"normalize")
 expect_error(feature_spec(length_range=c(2,1)),"range")
 expect_error(feature_spec(curvature_scale=0),"curvature_scale")
 expect_error(feature_spec(branch_window=2.5),"branch_window")
 expect_error(feature_spec(reference_radius=2),"mlv2023")
 expect_error(feature_spec(properties="separation",units="visual_degrees",pixels_per_degree=30),"branch_estimator")
 expect_s3_class(feature_spec(properties="separation",units="visual_degrees",pixels_per_degree=30,
  branch_estimator="arclength",reference_radius=.1,branch_window=.5),"mlv_feature_spec")
 expect_error(feature_spec(junction=list(unknown=1)),"junction")
 expect_error(feature_spec(mat=list(samples=3)),"samples")
 expect_error(feature_spec(mat=list(threshold_angle=91)),"threshold_angle")
 expect_error(feature_spec(mapping_radius=0),"mapping_radius")
 expect_error(feature_spec(extraction=list(thin=1)),"thin")
 expect_error(feature_spec(extraction=list(provider="test")),"together")
 expect_error(feature_spec(extraction=list(method="")),"method")
 expect_error(feature_spec(extraction=list(simplify=-1)),"simplify")
 expect_s3_class(feature_spec(extraction=list(provider="synthetic",provider_version="1",simplify=.2)),"mlv_feature_spec")
})
