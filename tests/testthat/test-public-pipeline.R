test_that("RGB file extraction reaches mapped MAT scores and selection", {
 skip_if_not_installed("png")
 image<-array(1,c(31,41,3));image[5:27,c(12,30),]<-0
 file<-tempfile(fileext=".png");png::writePNG(image,file)
 drawing<-trace_rgb(file,function(rgb)rgb[,,1]<.5)
 expect_equal(sort(vapply(drawing$contours,function(z)sum(sqrt(rowSums((z[,3:4,drop=FALSE]-z[,1:2,drop=FALSE])^2))),double(1))),c(22,22))
 simplified<-trace_contours(image,thin=FALSE,simplify=0)
 expect_equal(nrow(as.data.frame(simplified)),2)
 expect_identical(as_mlv_drawing(drawing),drawing)
 result<-analyse_mat(drawing,min_branch_points=2)
 expect_s3_class(result$mat,"mlv_mat")
 expect_output(print(result$mat),"skeleton pixels")
 expect_equal(dim(result$mat$skeleton),c(31L,41L))
 expect_true(any(is.finite(result$drawing$mat_images$parallelism)))
 density<-feature_density(result$drawing,"parallelism")
 expect_true(all(is.finite(density)))
 expect_true(any(density>0))
 parts<-split_contours(result$drawing,property="parallelism",fraction=1)
 expect_setequal(parts$top$ids,drawing$ids)
 expect_equal(split_contours(drawing,property="junctions")$scores,c("1"=1,"2"=2))
 expect_equal(split_contours(drawing,property="integrated_curvature")$scores,c("1"=1,"2"=2))
 set.seed(18);a<-split_contours(drawing,property="random")
 set.seed(18);b<-split_contours(drawing,property="random")
 expect_identical(a,b)
 plot_file<-tempfile(fileext=".png")
 grDevices::png(plot_file,width=700,height=400)
 tryCatch({
  old<-graphics::par("mfrow")
  plot_properties(result$drawing,c("parallelism","junctions"),columns=2)
  expect_identical(graphics::par("mfrow"),old)
  expect_error(plot(drawing,property="absent"),"unknown")
 },finally=grDevices::dev.off())
 expect_gt(file.info(plot_file)$size,0)
})
